CREATE TABLE IF NOT EXISTS pedido_arquivo (
  id INT NOT NULL AUTO_INCREMENT,
  order_id INT NOT NULL,
  tipo VARCHAR(10) NOT NULL DEFAULT 'outro',
  nome VARCHAR(120) NOT NULL,
  mime VARCHAR(60) NOT NULL,
  tamanho INT NOT NULL DEFAULT 0,
  dados LONGBLOB NOT NULL,
  criado_em DATETIME DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY ix_pedido_arquivo_order_id (order_id),
  CONSTRAINT fk_pedido_arquivo_order FOREIGN KEY (order_id) REFERENCES `order` (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS aviso_estoque (
  id INT NOT NULL AUTO_INCREMENT,
  user_id INT NOT NULL,
  product_id INT NOT NULL,
  criado_em DATETIME DEFAULT CURRENT_TIMESTAMP,
  avisado_em DATETIME NULL,
  PRIMARY KEY (id),
  KEY ix_aviso_estoque_user_id (user_id),
  KEY ix_aviso_estoque_product_id (product_id),
  CONSTRAINT fk_aviso_user FOREIGN KEY (user_id) REFERENCES `user` (id),
  CONSTRAINT fk_aviso_product FOREIGN KEY (product_id) REFERENCES product (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS lista_compra (
  id INT NOT NULL AUTO_INCREMENT,
  user_id INT NOT NULL,
  nome VARCHAR(60) NOT NULL,
  criada_em DATETIME DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY ix_lista_compra_user_id (user_id),
  CONSTRAINT fk_lista_user FOREIGN KEY (user_id) REFERENCES `user` (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS lista_item (
  id INT NOT NULL AUTO_INCREMENT,
  lista_id INT NOT NULL,
  product_id INT NOT NULL,
  qtd INT NOT NULL DEFAULT 1,
  PRIMARY KEY (id),
  KEY ix_lista_item_lista_id (lista_id),
  CONSTRAINT fk_lista_item_lista FOREIGN KEY (lista_id) REFERENCES lista_compra (id),
  CONSTRAINT fk_lista_item_product FOREIGN KEY (product_id) REFERENCES product (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS pedido_evento (
  id INT NOT NULL AUTO_INCREMENT,
  order_id INT NOT NULL,
  quando DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  autor VARCHAR(10) NOT NULL DEFAULT 'loja',
  autor_nome VARCHAR(120) DEFAULT '',
  texto VARCHAR(500) NOT NULL,
  PRIMARY KEY (id),
  KEY ix_pedido_evento_order_id (order_id),
  CONSTRAINT fk_pedido_evento_order FOREIGN KEY (order_id) REFERENCES `order` (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS order_item (
  id INT NOT NULL AUTO_INCREMENT,
  order_id INT NOT NULL,
  product_id INT NOT NULL,
  quantity INT NOT NULL,
  unit_price DECIMAL(10,2) NOT NULL,
  fracionado TINYINT(1) NOT NULL DEFAULT 0,
  custo_unitario DECIMAL(12,4) NULL,
  PRIMARY KEY (id),
  CONSTRAINT fk_item_order FOREIGN KEY (order_id) REFERENCES `order` (id),
  CONSTRAINT fk_item_product FOREIGN KEY (product_id) REFERENCES product (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS lancamento (
  id INT NOT NULL AUTO_INCREMENT,
  tipo VARCHAR(7) NOT NULL,
  descricao VARCHAR(160) DEFAULT '',
  categoria VARCHAR(40) DEFAULT '',
  valor DECIMAL(12,2) NOT NULL,
  vencimento DATE NOT NULL,
  pago_em DATE NULL,
  valor_pago DECIMAL(12,2) NULL,
  forma VARCHAR(20) DEFAULT '',
  parcela VARCHAR(10) DEFAULT '',
  order_id INT NULL,
  compra_id INT NULL,
  fornecedor_id INT NULL,
  observacao VARCHAR(300) DEFAULT '',
  criado_em DATETIME DEFAULT CURRENT_TIMESTAMP,
  boleto_id VARCHAR(30) NULL,
  boleto_link VARCHAR(300) DEFAULT '',
  boleto_linha VARCHAR(60) DEFAULT '',
  PRIMARY KEY (id),
  KEY ix_lancamento_boleto_id (boleto_id),
  KEY ix_lancamento_vencimento (vencimento),
  KEY ix_lancamento_pago_em (pago_em),
  KEY ix_lancamento_order_id (order_id),
  KEY ix_lancamento_compra_id (compra_id),
  KEY ix_lancamento_fornecedor_id (fornecedor_id),
  CONSTRAINT fk_lancamento_order FOREIGN KEY (order_id) REFERENCES `order` (id),
  CONSTRAINT fk_lancamento_compra FOREIGN KEY (compra_id) REFERENCES compra (id),
  CONSTRAINT fk_lancamento_fornecedor FOREIGN KEY (fornecedor_id) REFERENCES fornecedor (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS nota_recebida (
  id INT NOT NULL AUTO_INCREMENT,
  chave VARCHAR(44) NOT NULL,
  nsu VARCHAR(15) DEFAULT '',
  tipo VARCHAR(10) NOT NULL DEFAULT 'resumo',
  situacao VARCHAR(12) NOT NULL DEFAULT 'autorizada',
  cnpj_emitente VARCHAR(14) DEFAULT '',
  nome_emitente VARCHAR(160) DEFAULT '',
  numero INT NULL,
  serie INT NULL,
  valor DECIMAL(12,2) NOT NULL DEFAULT 0,
  emitida_em DATETIME NULL,
  manifestacao VARCHAR(12) DEFAULT '',
  origem VARCHAR(10) NOT NULL DEFAULT 'sefaz',
  xml MEDIUMTEXT,
  compra_id INT NULL,
  recebida_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_nota_recebida_chave (chave),
