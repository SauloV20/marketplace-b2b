-- Marketplace B2B · esquema e dados de exemplo (MySQL 8+)
-- Importar: mysql -u usuario -p < exemplo.sql
CREATE DATABASE IF NOT EXISTS marketplace CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE marketplace;
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS `user` (
  id INT NOT NULL AUTO_INCREMENT,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(120) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  is_admin TINYINT(1) NOT NULL DEFAULT 0,
  phone VARCHAR(30) DEFAULT '',
  address VARCHAR(300) DEFAULT '',
  email_verified TINYINT(1) NOT NULL DEFAULT 0,
  tipo VARCHAR(2) NOT NULL DEFAULT 'pf',
  documento VARCHAR(14) NULL,
  razao_social VARCHAR(160) DEFAULT '',
  inscricao_estadual VARCHAR(30) DEFAULT '',
  empresa_aprovada TINYINT(1) NOT NULL DEFAULT 0,
  desconto DECIMAL(5,2) NOT NULL DEFAULT 0,
  prazos VARCHAR(120) DEFAULT '',
  receita_situacao VARCHAR(40) DEFAULT '',
  receita_dados TEXT,
  receita_consultado_em DATETIME NULL,
  telefone_verificado TINYINT(1) NOT NULL DEFAULT 0,
  termos_aceitos_em DATETIME NULL,
  termos_versao VARCHAR(20) DEFAULT '',
  totp_segredo VARCHAR(64) DEFAULT '',
  totp_ultimo BIGINT NOT NULL DEFAULT 0,
  codigos_recuperacao TEXT NULL,
  permissoes VARCHAR(200) DEFAULT 'tudo',
  empresa_id INT NULL,
  papel VARCHAR(10) DEFAULT '',
  limite_aprovacao DECIMAL(12,2) NULL,
  limite_credito DECIMAL(12,2) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_user_email (email),
  UNIQUE KEY uq_user_documento (documento)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS endereco (
  id INT NOT NULL AUTO_INCREMENT,
  user_id INT NOT NULL,
  apelido VARCHAR(60) NOT NULL,
  cep VARCHAR(8) NOT NULL,
  endereco VARCHAR(300) NOT NULL,
  padrao TINYINT(1) NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  KEY ix_endereco_user_id (user_id),
  CONSTRAINT fk_endereco_user FOREIGN KEY (user_id) REFERENCES `user` (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS category (
  id INT NOT NULL AUTO_INCREMENT,
  name VARCHAR(80) NOT NULL,
  markup DECIMAL(6,2) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_category_name (name)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS product (
  id INT NOT NULL AUTO_INCREMENT,
  name VARCHAR(160) NOT NULL,
  description TEXT,
  price DECIMAL(10,2) NOT NULL,
  stock INT NOT NULL DEFAULT 0,
  image_url VARCHAR(500) DEFAULT '',
  active TINYINT(1) NOT NULL DEFAULT 1,
  category_id INT NOT NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  qtd_minima INT NOT NULL DEFAULT 1,
  multiplo INT NOT NULL DEFAULT 1,
  codigo VARCHAR(40) NULL,
  fracionavel TINYINT(1) NOT NULL DEFAULT 0,
  acrescimo_fracionado DECIMAL(5,2) NOT NULL DEFAULT 0,
  estoque_avulso INT NOT NULL DEFAULT 0,
  peso_kg DECIMAL(10,3) NOT NULL DEFAULT 0,
  estoque_alerta INT NOT NULL DEFAULT 0,
  preco_promocional DECIMAL(10,2) NULL,
  promo_inicio DATE NULL,
  promo_fim DATE NULL,
  preco_auto TINYINT(1) NOT NULL DEFAULT 0,
  markup DECIMAL(6,2) NULL,
  custo_medio DECIMAL(12,4) NULL,
  ncm VARCHAR(8) DEFAULT '',
  cest VARCHAR(7) DEFAULT '',
  origem INT NOT NULL DEFAULT 0,
  unidade VARCHAR(6) NOT NULL DEFAULT 'UN',
  ean VARCHAR(14) DEFAULT '',
  perfil_fiscal_id INT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_product_codigo (codigo),
  CONSTRAINT fk_product_category FOREIGN KEY (category_id) REFERENCES category (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `order` (
  id INT NOT NULL AUTO_INCREMENT,
  customer_name VARCHAR(120) NOT NULL,
  customer_email VARCHAR(120) DEFAULT '',
  customer_phone VARCHAR(30) DEFAULT '',
  address VARCHAR(300) DEFAULT '',
  payment_method VARCHAR(20) DEFAULT '',
  user_id INT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pendente',
  total DECIMAL(12,2) NOT NULL DEFAULT 0,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  documento VARCHAR(14) DEFAULT '',
  razao_social VARCHAR(160) DEFAULT '',
  inscricao_estadual VARCHAR(30) DEFAULT '',
  prazo VARCHAR(60) DEFAULT '',
  pix_txid VARCHAR(35) DEFAULT '',
  pix_copia_cola TEXT,
  pagador_nome VARCHAR(160) DEFAULT '',
  pagador_documento VARCHAR(20) DEFAULT '',
  pagador_confere TINYINT(1) NULL,
  cep VARCHAR(8) DEFAULT '',
  frete DECIMAL(10,2) NOT NULL DEFAULT 0,
  frete_prazo VARCHAR(60) DEFAULT '',
  frete_combinar TINYINT(1) NOT NULL DEFAULT 0,
  cupom VARCHAR(30) DEFAULT '',
  desconto DECIMAL(10,2) NOT NULL DEFAULT 0,
  envio VARCHAR(10) NOT NULL DEFAULT '',
  transportadora VARCHAR(80) DEFAULT '',
  rastreio VARCHAR(80) DEFAULT '',
  rastreio_link VARCHAR(300) DEFAULT '',
  enviado_em DATETIME NULL,
  entregue_em DATETIME NULL,
  comprador_id INT NULL,
  comprador_nome VARCHAR(120) DEFAULT '',
  PRIMARY KEY (id),
  KEY ix_order_created_at (created_at),
  KEY ix_order_cupom (cupom),
  KEY ix_order_user_id (user_id),
  CONSTRAINT fk_order_user FOREIGN KEY (user_id) REFERENCES `user` (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS cupom (
  id INT NOT NULL AUTO_INCREMENT,
  codigo VARCHAR(30) NOT NULL,
  tipo VARCHAR(10) NOT NULL DEFAULT 'percentual',
  valor DECIMAL(10,2) NOT NULL,
  minimo DECIMAL(12,2) NOT NULL DEFAULT 0,
  validade DATE NULL,
  limite_usos INT NULL,
  um_por_cliente TINYINT(1) NOT NULL DEFAULT 1,
  ativo TINYINT(1) NOT NULL DEFAULT 1,
  criado_em DATETIME DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_cupom_codigo (codigo)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS faixa_preco (
  id INT NOT NULL AUTO_INCREMENT,
  product_id INT NOT NULL,
  qtd_minima INT NOT NULL,
  preco DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (id),
  KEY ix_faixa_preco_product_id (product_id),
  CONSTRAINT fk_faixa_product FOREIGN KEY (product_id) REFERENCES product (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS fornecedor (
  id INT NOT NULL AUTO_INCREMENT,
  nome VARCHAR(160) NOT NULL,
  documento VARCHAR(14) DEFAULT '',
  uf VARCHAR(2) DEFAULT '',
  contato VARCHAR(120) DEFAULT '',
  telefone VARCHAR(30) DEFAULT '',
  email VARCHAR(120) DEFAULT '',
  observacoes TEXT,
  transporte VARCHAR(15) NOT NULL DEFAULT 'fornecedor',
  frete_pct DECIMAL(5,2) NOT NULL DEFAULT 0,
  custo_viagem DECIMAL(10,2) NOT NULL DEFAULT 0,
  compra_viagem DECIMAL(12,2) NOT NULL DEFAULT 0,
  credito_pct DECIMAL(5,2) NOT NULL DEFAULT 0,
  ativo TINYINT(1) NOT NULL DEFAULT 1,
  criado_em DATETIME DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS produto_fornecedor (
  id INT NOT NULL AUTO_INCREMENT,
  product_id INT NOT NULL,
  fornecedor_id INT NOT NULL,
  codigo VARCHAR(60) DEFAULT '',
  preco_compra DECIMAL(12,4) NOT NULL,
  ipi_pct DECIMAL(5,2) NOT NULL DEFAULT 0,
  st_pct DECIMAL(5,2) NOT NULL DEFAULT 0,
  principal TINYINT(1) NOT NULL DEFAULT 0,
  fator INT NOT NULL DEFAULT 1,
  atualizado_em DATETIME DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_produto_fornecedor (product_id, fornecedor_id),
  KEY ix_produto_fornecedor_product_id (product_id),
  KEY ix_produto_fornecedor_fornecedor_id (fornecedor_id),
  CONSTRAINT fk_custo_product FOREIGN KEY (product_id) REFERENCES product (id),
  CONSTRAINT fk_custo_fornecedor FOREIGN KEY (fornecedor_id) REFERENCES fornecedor (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS movimento_estoque (
  id INT NOT NULL AUTO_INCREMENT,
  product_id INT NOT NULL,
  quando DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  tipo VARCHAR(20) NOT NULL,
  quantidade INT NOT NULL,
  saldo INT NULL,
  custo_unitario DECIMAL(12,4) NULL,
  order_id INT NULL,
  compra_id INT NULL,
  autor VARCHAR(120) DEFAULT '',
  observacao VARCHAR(200) DEFAULT '',
  PRIMARY KEY (id),
  KEY ix_movimento_estoque_product_id (product_id),
  KEY ix_movimento_estoque_quando (quando),
  KEY ix_movimento_estoque_order_id (order_id),
  KEY ix_movimento_estoque_compra_id (compra_id),
  CONSTRAINT fk_movimento_product FOREIGN KEY (product_id) REFERENCES product (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS compra (
  id INT NOT NULL AUTO_INCREMENT,
  fornecedor_id INT NOT NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'rascunho',
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  enviado_em DATETIME NULL,
  recebido_em DATETIME NULL,
  previsao DATE NULL,
  condicao VARCHAR(60) DEFAULT '',
  frete DECIMAL(10,2) NOT NULL DEFAULT 0,
  nota VARCHAR(60) DEFAULT '',
  observacoes TEXT,
  autor VARCHAR(120) DEFAULT '',
  PRIMARY KEY (id),
  KEY ix_compra_fornecedor_id (fornecedor_id),
  CONSTRAINT fk_compra_fornecedor FOREIGN KEY (fornecedor_id) REFERENCES fornecedor (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS compra_item (
  id INT NOT NULL AUTO_INCREMENT,
  compra_id INT NOT NULL,
  product_id INT NOT NULL,
  quantidade INT NOT NULL,
  preco DECIMAL(12,4) NOT NULL,
  ipi_pct DECIMAL(5,2) NOT NULL DEFAULT 0,
  st_pct DECIMAL(5,2) NOT NULL DEFAULT 0,
  recebido INT NULL,
  PRIMARY KEY (id),
  KEY ix_compra_item_compra_id (compra_id),
  KEY ix_compra_item_product_id (product_id),
  CONSTRAINT fk_compra_item_compra FOREIGN KEY (compra_id) REFERENCES compra (id),
  CONSTRAINT fk_compra_item_product FOREIGN KEY (product_id) REFERENCES product (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS imposto_uf (
  uf VARCHAR(2) NOT NULL,
  icms DECIMAL(5,2) NULL,
  adicional DECIMAL(5,2) NULL,
  entrega VARCHAR(15) NOT NULL DEFAULT 'transportadora',
  custo_entrega DECIMAL(5,2) NOT NULL DEFAULT 0,
  PRIMARY KEY (uf)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS importacao_pendente (
  id INT NOT NULL AUTO_INCREMENT,
  criado_em DATETIME DEFAULT CURRENT_TIMESTAMP,
  nome_arquivo VARCHAR(200) DEFAULT '',
  conteudo LONGBLOB NOT NULL,
  desativar_ausentes TINYINT(1) NOT NULL DEFAULT 0,
  PRIMARY KEY (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS produto_foto (
  id INT NOT NULL AUTO_INCREMENT,
  product_id INT NOT NULL,
  dados MEDIUMBLOB NOT NULL,
  tipo VARCHAR(30) NOT NULL,
  ordem INT NOT NULL DEFAULT 0,
  versao INT NOT NULL DEFAULT 1,
  PRIMARY KEY (id),
  KEY ix_produto_foto_product_id (product_id),
  CONSTRAINT fk_foto_product FOREIGN KEY (product_id) REFERENCES product (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS banner (
  id INT NOT NULL AUTO_INCREMENT,
  titulo VARCHAR(120) DEFAULT '',
  subtitulo VARCHAR(200) DEFAULT '',
  texto_botao VARCHAR(40) DEFAULT '',
  link VARCHAR(500) DEFAULT '',
  product_id INT NULL,
  imagem MEDIUMBLOB NULL,
  imagem_tipo VARCHAR(30) DEFAULT '',
  imagem_url VARCHAR(500) DEFAULT '',
  cor VARCHAR(20) DEFAULT 'azul',
  ordem INT NOT NULL DEFAULT 0,
  ativo TINYINT(1) NOT NULL DEFAULT 1,
  versao INT NOT NULL DEFAULT 1,
  PRIMARY KEY (id),
  CONSTRAINT fk_banner_product FOREIGN KEY (product_id) REFERENCES product (id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS pergunta (
  id INT NOT NULL AUTO_INCREMENT,
  pergunta VARCHAR(200) NOT NULL,
  resposta TEXT NOT NULL,
  ordem INT NOT NULL DEFAULT 0,
  ativo TINYINT(1) NOT NULL DEFAULT 1,
  PRIMARY KEY (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS regra_frete (
  id INT NOT NULL AUTO_INCREMENT,
  nome VARCHAR(80) NOT NULL,
  ufs VARCHAR(120) DEFAULT '',
  cep_de INT NULL,
  cep_ate INT NULL,
  valor DECIMAL(10,2) NOT NULL DEFAULT 0,
  valor_kg DECIMAL(10,2) NOT NULL DEFAULT 0,
  gratis_acima DECIMAL(12,2) NULL,
  prazo VARCHAR(60) DEFAULT '',
  ordem INT NOT NULL DEFAULT 0,
  ativo TINYINT(1) NOT NULL DEFAULT 1,
  PRIMARY KEY (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS configuracao (
  chave VARCHAR(40) NOT NULL,
  valor VARCHAR(200) DEFAULT '',
  PRIMARY KEY (chave)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS limite_uso (
  id INT NOT NULL AUTO_INCREMENT,
  chave VARCHAR(64) NOT NULL,
  momento BIGINT NOT NULL,
  PRIMARY KEY (id),
  KEY ix_limite_uso_chave (chave),
  KEY ix_limite_uso_momento (momento)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS login_falha (
  chave VARCHAR(64) NOT NULL,
  falhas INT NOT NULL DEFAULT 0,
  ultima BIGINT NOT NULL DEFAULT 0,
  bloqueado_ate BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY (chave)
