CREATE TABLE IF NOT EXISTS nota_fiscal (
  id INT NOT NULL AUTO_INCREMENT,
  order_id INT NULL,
  ambiente INT NOT NULL,
  serie INT NOT NULL,
  numero INT NOT NULL,
  chave VARCHAR(44) DEFAULT '',
  status VARCHAR(12) NOT NULL DEFAULT 'processando',
  cstat VARCHAR(4) DEFAULT '',
  motivo VARCHAR(500) DEFAULT '',
  protocolo VARCHAR(20) DEFAULT '',
  xml MEDIUMTEXT,
  valor DECIMAL(12,2) NOT NULL DEFAULT 0,
  destinatario VARCHAR(160) DEFAULT '',
  provedor VARCHAR(20) DEFAULT '',
  autor VARCHAR(120) DEFAULT '',
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  autorizada_em DATETIME NULL,
  cancelada_em DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_nota_numero (ambiente, serie, numero),
  KEY ix_nota_fiscal_order_id (order_id),
  KEY ix_nota_fiscal_chave (chave),
  KEY ix_nota_fiscal_criado_em (criado_em),
  CONSTRAINT fk_nota_order FOREIGN KEY (order_id) REFERENCES `order` (id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS nota_evento (
  id INT NOT NULL AUTO_INCREMENT,
  nota_id INT NULL,
  tipo VARCHAR(15) NOT NULL,
  sequencia INT NOT NULL DEFAULT 1,
  texto VARCHAR(1000) DEFAULT '',
  ok TINYINT(1) NOT NULL DEFAULT 0,
  cstat VARCHAR(4) DEFAULT '',
  motivo VARCHAR(500) DEFAULT '',
  protocolo VARCHAR(20) DEFAULT '',
  xml MEDIUMTEXT,
  quando DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  autor VARCHAR(120) DEFAULT '',
  PRIMARY KEY (id),
  KEY ix_nota_evento_nota_id (nota_id),
  CONSTRAINT fk_evento_nota FOREIGN KEY (nota_id) REFERENCES nota_fiscal (id)
) ENGINE=InnoDB;

